#!/usr/bin/env node
/**
 * Generate supabase/tests/database/entitlement_parity.test.sql from
 * tests/fixtures/entitlement-cases.json, so the SQL predicate
 * (public.subscription_tier_for / public.user_subscription_tier) is checked
 * against the same cases as the client and Edge predicates.
 *
 *   node scripts/gen-entitlement-parity-test.mjs          # rewrite the test
 *   node scripts/gen-entitlement-parity-test.mjs --check  # exit 1 if stale
 *
 * src/lib/subscription-entitlement.test.ts compares the committed file with
 * renderEntitlementParityTest(fixture), so editing the fixture without
 * regenerating fails `npm test`. The test declares plan(n) from the case
 * count, so a generator that drops a case fails pgTAP.
 */
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = path.resolve(
	path.dirname(fileURLToPath(import.meta.url)),
	"..",
);
const fixturePath = path.join(
	repoRoot,
	"tests",
	"fixtures",
	"entitlement-cases.json",
);
const outputPath = path.join(
	repoRoot,
	"supabase",
	"tests",
	"database",
	"entitlement_parity.test.sql",
);

const sqlText = (value) => `'${String(value).replaceAll("'", "''")}'`;

function userIdFor(index) {
	return `e8000000-0000-4000-8000-${String(index + 1).padStart(12, "0")}`;
}

function periodEndSql(offsetSeconds) {
	if (offsetSeconds === null) return "NULL";
	if (!Number.isInteger(offsetSeconds)) {
		throw new Error(`periodEndOffsetSeconds must be an integer or null`);
	}
	return `now() + make_interval(secs => ${offsetSeconds})`;
}

const CATALOG_SIGNATURES = [
	"subscription_tier_for(uuid)",
	"user_subscription_tier()",
];

const GRANTS = [
	["authenticated", "user_subscription_tier()", true],
	["service_role", "user_subscription_tier()", true],
	["anon", "user_subscription_tier()", false],
	["service_role", "subscription_tier_for(uuid)", true],
	["authenticated", "subscription_tier_for(uuid)", false],
	["anon", "subscription_tier_for(uuid)", false],
];

export function renderEntitlementParityTest(fixture) {
	const cases = fixture.cases;
	// 2 per catalog signature, 1 per grant, 2 per case (service_role +
	// authenticated), NULL user, authenticated direct-call denial.
	const planCount =
		CATALOG_SIGNATURES.length * 2 + GRANTS.length + cases.length * 2 + 2;
	const lines = [];
	const push = (...xs) => lines.push(...xs);

	push(
		"-- GENERATED by scripts/gen-entitlement-parity-test.mjs from",
		"-- tests/fixtures/entitlement-cases.json. Do not edit by hand; edit the",
		"-- fixture and rerun the script.",
		"--",
		"-- Runs the shared entitlement fixture through public.subscription_tier_for",
		"-- (service_role) and public.user_subscription_tier() (authenticated), and",
		"-- pins both as SECURITY DEFINER with the expected grants. now() is frozen",
		"-- for the transaction, so the ±1 s boundary rows are exact.",
		`-- Fixture graceHours: ${fixture.graceHours}.`,
		"",
		"BEGIN;",
		"",
		"CREATE EXTENSION IF NOT EXISTS pgtap WITH SCHEMA extensions;",
		"SET LOCAL search_path = public, extensions;",
		"",
		`SELECT plan(${planCount});`,
		"",
		"SELECT diag('database:entitlement-parity-catalog');",
		"",
	);

	for (const sig of CATALOG_SIGNATURES) {
		push(
			"SELECT ok(",
			`    (SELECT p.prosecdef FROM pg_proc p WHERE p.oid = 'public.${sig}'::regprocedure),`,
			`    '${sig} is SECURITY DEFINER'`,
			");",
			"SELECT ok(",
			`    (SELECT 'search_path=""' = ANY (p.proconfig) FROM pg_proc p WHERE p.oid = 'public.${sig}'::regprocedure),`,
			`    '${sig} pins search_path'`,
			");",
		);
	}

	for (const [role, sig, allowed] of GRANTS) {
		push(
			"SELECT is(",
			`    has_function_privilege('${role}', 'public.${sig}', 'EXECUTE'),`,
			`    ${allowed},`,
			`    '${role} ${allowed ? "may" : "may not"} execute ${sig}'`,
			");",
		);
	}

	push(
		"",
		"-- Unknown-tier rows (legacy PHOENIX/ELITE) are blocked by the tier CHECK;",
		"-- drop it for this transaction only so the predicate's own tier filter is",
		"-- exercised. ROLLBACK below restores it.",
		"ALTER TABLE public.subscriptions DROP CONSTRAINT IF EXISTS subscriptions_tier_check;",
		"",
		"INSERT INTO auth.users (id, email)",
		"VALUES",
		cases
			.map(
				(c, i) =>
					`    ('${userIdFor(i)}'::uuid, ${sqlText(`entitlement-${c.id}@example.test`)})`,
			)
			.join(",\n"),
		"ON CONFLICT (id) DO NOTHING;",
		"",
		"INSERT INTO public.subscriptions (user_id, tier, status, current_period_end, cancel_at_period_end)",
		"VALUES",
		cases
			.map(
				(c, i) =>
					`    ('${userIdFor(i)}'::uuid, ${sqlText(c.tier)}, ${sqlText(c.status)}, ${periodEndSql(c.periodEndOffsetSeconds)}, ${c.cancelAtPeriodEnd === true})`,
			)
			.join(",\n"),
		"ON CONFLICT (user_id) DO UPDATE",
		"SET tier = EXCLUDED.tier,",
		"    status = EXCLUDED.status,",
		"    current_period_end = EXCLUDED.current_period_end,",
		"    cancel_at_period_end = EXCLUDED.cancel_at_period_end;",
		"",
		"SELECT diag('database:entitlement-parity-service-role');",
		"",
		"SET LOCAL ROLE service_role;",
		"",
	);

	cases.forEach((c, i) => {
		push(
			`SELECT is(public.subscription_tier_for('${userIdFor(i)}'::uuid), ${sqlText(c.expectedTier)}, ${sqlText(`subscription_tier_for: ${c.id}`)});`,
		);
	});

	push(
		"SELECT is(public.subscription_tier_for(NULL), 'FREE', 'subscription_tier_for: NULL user is FREE');",
		"",
		"RESET ROLE;",
		"",
		"SELECT diag('database:entitlement-parity-authenticated');",
		"",
		"SET LOCAL ROLE authenticated;",
		"",
		"SELECT throws_ok(",
		`    $sql$ SELECT public.subscription_tier_for('${userIdFor(0)}'::uuid) $sql$,`,
		"    '42501',",
		"    NULL,",
		"    'authenticated cannot call subscription_tier_for directly'",
		");",
		"",
	);

	cases.forEach((c, i) => {
		push(
			`SELECT set_config('request.jwt.claims', '{"sub":"${userIdFor(i)}","role":"authenticated"}', true);`,
			`SELECT is(public.user_subscription_tier(), ${sqlText(c.expectedTier)}, ${sqlText(`user_subscription_tier: ${c.id}`)});`,
		);
	});

	push(
		"",
		"SELECT set_config('request.jwt.claims', '', true);",
		"RESET ROLE;",
		"",
		"SELECT * FROM finish();",
		"",
		"ROLLBACK;",
		"",
	);

	return lines.join("\n");
}

const isMain =
	process.argv[1] &&
	path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);

if (isMain) {
	const fixture = JSON.parse(readFileSync(fixturePath, "utf8"));
	const rendered = renderEntitlementParityTest(fixture);
	if (process.argv.includes("--check")) {
		let current = "";
		try {
			current = readFileSync(outputPath, "utf8").replaceAll("\r\n", "\n");
		} catch {
			// missing file counts as stale
		}
		if (current !== rendered) {
			console.error(
				"supabase/tests/database/entitlement_parity.test.sql is stale. Run: node scripts/gen-entitlement-parity-test.mjs",
			);
			process.exit(1);
		}
		console.log("entitlement_parity.test.sql is up to date.");
	} else {
		writeFileSync(outputPath, rendered);
		console.log(`Wrote ${path.relative(repoRoot, outputPath)}`);
	}
}
