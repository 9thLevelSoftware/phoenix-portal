import { execFile as execFileCallback } from "node:child_process";
import { mkdir, mkdtemp, readFile, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { promisify } from "node:util";
import { config as loadDotenv } from "dotenv";

const execFile = promisify(execFileCallback);

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(__dirname, "..");
const baseConfigPath = path.join(repoRoot, "supabase", "config.toml");

loadDotenv({ path: path.join(repoRoot, ".env"), override: false });
loadDotenv({ path: path.join(repoRoot, ".env.local"), override: true });

export const DEFAULT_LOCAL_SITE_URL = "http://localhost:5173";
export const OAUTH_CALLBACK_PATH = "/auth/callback";
export const SUPABASE_CALLBACK_PATH = "/auth/v1/callback";
export const MANAGED_BLOCK_START = "# BEGIN_MANAGED_SOCIAL_AUTH";
export const MANAGED_BLOCK_END = "# END_MANAGED_SOCIAL_AUTH";

function quoteTomlString(value) {
	return JSON.stringify(value);
}

function toDisplayList(items) {
	return items.map((item) => `  - ${item}`).join("\n");
}

export function inferProjectRef({
	projectRef = process.env.SUPABASE_PROJECT_REF,
	supabaseUrl = process.env.VITE_SUPABASE_URL,
} = {}) {
	if (projectRef) {
		return projectRef.trim();
	}

	if (!supabaseUrl) {
		throw new Error(
			"Missing SUPABASE_PROJECT_REF and VITE_SUPABASE_URL; cannot infer the Supabase project ref.",
		);
	}

	const hostname = new URL(supabaseUrl).hostname;
	const [ref] = hostname.split(".");

	if (!ref) {
		throw new Error(`Could not infer a project ref from ${supabaseUrl}.`);
	}

	return ref;
}

export function parseCsvUrls(value = "") {
	const uniqueUrls = new Set();

	for (const rawValue of value.split(",")) {
		const trimmed = rawValue.trim();
		if (!trimmed) {
			continue;
		}

		uniqueUrls.add(new URL(trimmed).toString());
	}

	return [...uniqueUrls];
}

export function buildPortalCallbackUrl(siteUrl) {
	return new URL(OAUTH_CALLBACK_PATH, siteUrl).toString();
}

export function buildAllowedRedirectUrls({
	siteUrl,
	additionalRedirectUrls = "",
} = {}) {
	const allowedRedirectUrls = new Set([
		buildPortalCallbackUrl(DEFAULT_LOCAL_SITE_URL),
		buildPortalCallbackUrl(siteUrl),
	]);

	for (const redirectUrl of parseCsvUrls(additionalRedirectUrls)) {
		allowedRedirectUrls.add(redirectUrl);
	}

	return [...allowedRedirectUrls];
}

export function buildManagedSocialAuthBlock({
	siteUrl,
	allowedRedirectUrls,
	googleClientId,
	googleSecret,
	appleClientId,
	appleSecret,
}) {
	const redirectUrlList = allowedRedirectUrls
		.map((redirectUrl) => `  ${quoteTomlString(redirectUrl)},`)
		.join("\n");

	return `${MANAGED_BLOCK_START}
# Generated by scripts/sync-social-auth.mjs for hosted social auth.
site_url = ${quoteTomlString(siteUrl)}
additional_redirect_urls = [
${redirectUrlList}
]

[auth.external.google]
enabled = true
client_id = ${quoteTomlString(googleClientId)}
secret = ${quoteTomlString(googleSecret)}
skip_nonce_check = false

[auth.external.apple]
enabled = true
client_id = ${quoteTomlString(appleClientId)}
secret = ${quoteTomlString(appleSecret)}
# END_MANAGED_SOCIAL_AUTH`;
}

export function buildManagedConfig(baseConfig, options) {
	const startIndex = baseConfig.indexOf(MANAGED_BLOCK_START);
	const endIndex = baseConfig.indexOf(MANAGED_BLOCK_END);

	if (startIndex === -1 || endIndex === -1 || endIndex < startIndex) {
		throw new Error(
			"supabase/config.toml is missing the managed social auth placeholder block.",
		);
	}

	const afterEndIndex = endIndex + MANAGED_BLOCK_END.length;
	return `${baseConfig.slice(0, startIndex)}${buildManagedSocialAuthBlock(options)}${baseConfig.slice(afterEndIndex)}`;
}

function getPushInputs() {
	const requiredEnvVars = [
		"SUPABASE_AUTH_SITE_URL",
		"SUPABASE_AUTH_EXTERNAL_GOOGLE_CLIENT_ID",
		"SUPABASE_AUTH_EXTERNAL_GOOGLE_SECRET",
		"SUPABASE_AUTH_EXTERNAL_APPLE_CLIENT_ID",
		"SUPABASE_AUTH_EXTERNAL_APPLE_SECRET",
	];
	const missingEnvVars = requiredEnvVars.filter(
		(name) => !process.env[name]?.trim(),
	);

	if (missingEnvVars.length > 0) {
		throw new Error(
			`Missing required environment variables:\n${toDisplayList(missingEnvVars)}`,
		);
	}

	const siteUrl = process.env.SUPABASE_AUTH_SITE_URL.trim();
	const googleClientId =
		process.env.SUPABASE_AUTH_EXTERNAL_GOOGLE_CLIENT_ID.trim();
	const googleSecret = process.env.SUPABASE_AUTH_EXTERNAL_GOOGLE_SECRET.trim();
	const appleClientId =
		process.env.SUPABASE_AUTH_EXTERNAL_APPLE_CLIENT_ID.trim();
	const appleSecret = process.env.SUPABASE_AUTH_EXTERNAL_APPLE_SECRET.trim();

	return {
		siteUrl: new URL(siteUrl).toString(),
		allowedRedirectUrls: buildAllowedRedirectUrls({
			siteUrl,
			additionalRedirectUrls:
				process.env.SUPABASE_AUTH_ADDITIONAL_REDIRECT_URLS ?? "",
		}),
		googleClientId,
		googleSecret,
		appleClientId,
		appleSecret,
	};
}

export async function fetchPublicAuthSettings({
	supabaseUrl = process.env.VITE_SUPABASE_URL,
	supabaseAnonKey = process.env.VITE_SUPABASE_ANON_KEY,
} = {}) {
	if (!supabaseUrl || !supabaseAnonKey) {
		throw new Error(
			"Missing VITE_SUPABASE_URL or VITE_SUPABASE_ANON_KEY; cannot verify public auth settings.",
		);
	}

	const response = await fetch(`${supabaseUrl}/auth/v1/settings`, {
		headers: {
			apikey: supabaseAnonKey,
			Authorization: `Bearer ${supabaseAnonKey}`,
		},
	});

	if (!response.ok) {
		throw new Error(
			`Public auth settings request failed with status ${response.status}.`,
		);
	}

	return response.json();
}

function printSetupChecklist({ projectRef, siteUrl, allowedRedirectUrls }) {
	const siteOrigin = new URL(siteUrl).origin;
	const callbackUrl = `https://${projectRef}.supabase.co${SUPABASE_CALLBACK_PATH}`;

	console.log("Social auth provider console values:");
	console.log(`  Supabase callback URL: ${callbackUrl}`);
	console.log(
		`  Google JavaScript origins: ${siteOrigin}, ${DEFAULT_LOCAL_SITE_URL}`,
	);
	console.log(`  Apple website URL: https://${projectRef}.supabase.co`);
	console.log("  Allowed portal redirect URLs:");
	console.log(toDisplayList(allowedRedirectUrls));
}

async function pushHostedConfig(projectRef, managedConfig) {
	const tempRoot = await mkdtemp(
		path.join(tmpdir(), "phoenix-portal-social-auth-"),
	);
	const tempWorkdir = path.join(tempRoot, "workdir");
	const tempSupabaseDir = path.join(tempWorkdir, "supabase");
	const npxCommand = process.platform === "win32" ? "npx.cmd" : "npx";

	try {
		await mkdir(tempSupabaseDir, { recursive: true });
		await writeFile(path.join(tempSupabaseDir, "config.toml"), managedConfig);

		const { stdout, stderr } = await execFile(
			npxCommand,
			["supabase", "config", "push", "--project-ref", projectRef, "--yes"],
			{
				cwd: tempWorkdir,
				env: process.env,
				// Windows requires shell: true to spawn .cmd shims (Node 20+ security).
				shell: process.platform === "win32",
			},
		);

		if (stdout.trim()) {
			console.log(stdout.trim());
		}

		if (stderr.trim()) {
			console.error(stderr.trim());
		}
	} finally {
		await rm(tempRoot, { recursive: true, force: true });
	}
}

async function runCheck() {
	const projectRef = inferProjectRef();
	const settings = await fetchPublicAuthSettings();

	console.log(`Supabase project: ${projectRef}`);
	console.log("Current public auth provider state:");
	console.log(
		`  Google: ${settings.external?.google === true ? "enabled" : "disabled"}`,
	);
	console.log(
		`  Apple: ${settings.external?.apple === true ? "enabled" : "disabled"}`,
	);
}

async function runPush() {
	const projectRef = inferProjectRef();
	const pushInputs = getPushInputs();
	const baseConfig = await readFile(baseConfigPath, "utf8");
	const managedConfig = buildManagedConfig(baseConfig, pushInputs);

	printSetupChecklist({
		projectRef,
		siteUrl: pushInputs.siteUrl,
		allowedRedirectUrls: pushInputs.allowedRedirectUrls,
	});

	await pushHostedConfig(projectRef, managedConfig);
	await runCheck();
}

async function main() {
	const command = process.argv[2] ?? "check";

	if (command === "push") {
		await runPush();
		return;
	}

	if (command === "check") {
		await runCheck();
		return;
	}

	throw new Error(`Unknown command "${command}". Use "check" or "push".`);
}

const isMainModule =
	process.argv[1] != null &&
	pathToFileURL(path.resolve(process.argv[1])).href === import.meta.url;

if (isMainModule) {
	try {
		await main();
	} catch (error) {
		const message =
			error instanceof Error ? error.message : "Unknown social auth failure.";
		console.error(message);
		process.exitCode = 1;
	}
}
